/**
 * The pure half of bench/jev-drift-store.mjs: how a stored locator chain is
 * DRIFTED, and how a heal's answer is then scored against the chain it
 * replaced.
 *
 * Why it is a separate module: everything here is a function of JSON and
 * nothing here opens a browser, spends a token or reads the clock, so it can
 * be unit-tested (test/jev-drift-lib.test.ts) and read as the definition of
 * what the calibration measures. The driver script is the part that resets
 * apps, spawns the CLI and prints tables.
 *
 * It is NOT a repair tool, a store migration, or anything that may run against
 * a store somebody cares about: `perturbChain` deliberately produces a chain
 * that finds NOTHING, and the driver only ever applies it to a throwaway copy.
 *
 * THE TWO IDEAS
 *
 * 1. Drift the STORE, not the app. We cannot rename a control inside Odoo, but
 *    from the healer's point of view "the app renamed the control" and "the
 *    stored chain describes the control by names the app no longer uses" are
 *    the same situation: every rung misses and the live page holds the real
 *    control. So a case is a copy of a store with ONE step's chain rewritten
 *    to a plausible OLD description of the same control.
 *
 * 2. Ground truth is free, because the app did not move. The ORIGINAL chain
 *    still names the right element, and it names it several ways at once
 *    (testid, role+name, label, id — the recorder's own candidate order). So a
 *    proposal is CORRECT when it agrees with any rung of the original chain on
 *    an identifying field, and WRONG when it contradicts one: an element has
 *    exactly one data-testid, one id, and one accessible name. Where neither
 *    holds the case is UNDECIDABLE and is counted in neither column — a
 *    calibration that guesses its own labels is worth less than no calibration.
 */

// --- the wording a rename comes from -----------------------------------------

/**
 * Renames actually seen in this repo's drift history, as a synonym table:
 * `add-part` -> `part-attach` "Add part" -> "Attach part" (the one real
 * repairdesk drift), plus the vocabulary the four bench apps use for the same
 * few verbs. Deliberately NOT generated by a model: a calibration whose
 * difficulty is set by an LLM's taste in synonyms cannot be reproduced, and
 * the transform family is an analysis dimension (a synonym rename is a harder
 * case than a punctuation change and has to be countable as such).
 *
 * Each row is a set of words that name the same thing; the transform swaps a
 * word for the NEXT one in its row, so the mapping is a deterministic rotation
 * rather than a choice.
 */
export const SYNONYM_ROWS = [
  ['add', 'attach', 'new', 'create'],
  ['save', 'submit', 'apply', 'confirm'],
  ['delete', 'remove', 'discard'],
  ['edit', 'modify', 'change', 'update'],
  ['search', 'filter', 'find'],
  ['customer', 'client', 'contact'],
  ['ticket', 'case', 'job'],
  ['part', 'item', 'component'],
  ['open', 'view', 'show'],
  ['close', 'dismiss', 'hide'],
  ['cancel', 'back'],
  ['title', 'name', 'subject'],
  ['note', 'comment', 'remark'],
  ['order', 'quotation', 'quote'],
  ['task', 'card'],
  ['board', 'project'],
  ['dashboard', 'panel'],
  ['report', 'summary'],
  ['send', 'post'],
  ['sign', 'log'],
  ['price', 'cost', 'amount'],
  ['status', 'state'],
  ['user', 'member', 'account'],
  ['settings', 'preferences', 'options'],
  ['row', 'line', 'entry'],
  ['email', 'e-mail'],
  ['password', 'passphrase'],
  ['description', 'details'],
  ['due', 'deadline'],
  ['assignee', 'owner'],
  ['column', 'list'],
  ['swimlane', 'lane'],
  ['tag', 'label'],
  ['markup', 'margin'],
  ['total', 'sum'],
  ['reference', 'ref'],
  ['visualization', 'graph'],
  ['query', 'expression'],
];

/**
 * Symbols and abbreviations a form outgrows. Kept apart from the synonym rows
 * because these are the tokens the word-level pass cannot see — `%` and `#`
 * survive no `[^A-Za-z]` strip — and because the expansion direction is the
 * realistic one: forms get terser, so the FORMER wording is the long one.
 */
const ABBREVIATIONS = [
  ['%', 'percent'],
  ['#', 'number'],
  ['&', 'and'],
  ['qty', 'quantity'],
  ['no.', 'number'],
  ['id', 'reference'],
];

const SYNONYM_OF = (() => {
  const map = new Map();
  for (const row of SYNONYM_ROWS) {
    for (let i = 0; i < row.length; i++) map.set(row[i], row[(i + 1) % row.length]);
  }
  return map;
})();

/** Every transform family the report splits on. Order is difficulty order, easiest last. */
export const TRANSFORM_FAMILIES = ['synonym', 'affix', 'punctuation', 'stale-id', 'stale-path', 'moved-path', 'moved', 'dead', 'none'];

/** Keep the casing shape of the word being replaced: Save -> Submit, SAVE -> SUBMIT, save -> submit. */
function matchCase(sample, word) {
  if (sample === sample.toUpperCase() && sample !== sample.toLowerCase()) return word.toUpperCase();
  if (sample[0] === sample[0]?.toUpperCase()) return word[0].toUpperCase() + word.slice(1);
  return word;
}

/**
 * A plausible former WORDING for a human-facing string: an accessible name, a
 * label, a placeholder, a button's text.
 *
 * Tried in difficulty order, hardest first, and the first that actually
 * changes the string wins — so a string with a synonym in it becomes a synonym
 * case and only a string with no vocabulary to swap falls through to the
 * shapes that are nearly free to see through.
 *
 *  synonym      "Add part"  -> "Attach part"   (a control was renamed)
 *  affix        "Title *"   -> "Title"         (a suffix/prefix came or went)
 *  punctuation  "Save"      -> "Save…"         (cosmetic, the easy case)
 */
export function driftWording(text) {
  if (!text || /\{\{/.test(text)) return null;
  /**
   * A drifted name that is a SUBSTRING of the real one is not dead.
   * `getByLabel` and `getByPlaceholder` match a substring by default
   * (`volatileMatcher` returns a plain string when the name carries nothing
   * volatile), so "Markup % *" drifted to "Markup %" still finds the very
   * control it was supposed to stop finding — a case that silently is not a
   * case. The other direction is safe: a LONGER name is contained by nothing.
   */
  const dead = (out) => out && out !== text && !text.includes(out);
  const candidates = [];

  const words = text.split(/(\s+)/);
  for (let i = 0; i < words.length; i++) {
    const bare = words[i].replace(/[^A-Za-z]/g, '');
    if (!bare) continue;
    const swap = SYNONYM_OF.get(bare.toLowerCase());
    if (!swap) continue;
    const next = words.slice();
    next[i] = words[i].replace(bare, matchCase(bare, swap));
    candidates.push({ value: next.join(''), transform: 'synonym' });
  }
  for (const [short, long] of ABBREVIATIONS) {
    if (!text.toLowerCase().includes(short)) continue;
    candidates.push({ value: text.replace(short, long), transform: 'synonym' });
    candidates.push({ value: text.replace(short, ` ${long}`).replace(/\s+/g, ' ').trim(), transform: 'synonym' });
  }
  const parts = text.trim().split(/\s+/);
  // The trailing token is the one a form adds and drops: a required marker, a
  // unit, a count. Dropping it is the commonest real rename — and usually
  // leaves a substring, so it is offered rather than taken.
  if (parts.length > 1) candidates.push({ value: parts.slice(0, -1).join(' '), transform: 'affix' });
  candidates.push({ value: text.replace(/[.:…*\s]+$/, ''), transform: 'punctuation' });
  candidates.push({ value: `${text}…`, transform: 'punctuation' });
  // Last resort, and never a substring of anything: a version suffix.
  candidates.push({ value: `${text} v1`, transform: 'affix' });
  return candidates.find((c) => dead(c.value)) ?? null;
}

/**
 * A plausible former IDENTIFIER: a testid, an id, the value inside an
 * attribute selector. Same synonym table applied to the word tokens of a
 * kebab/snake/camel name, so `add-part` drifts to `attach-part` and the whole
 * chain tells one coherent story; a name with no vocabulary in it gets the
 * stale-value treatment, which is what a regenerated build id looks like.
 */
export function driftIdentifier(value) {
  if (!value || /\{\{/.test(value)) return null;
  const tokens = value.split(/([^A-Za-z0-9]+|(?<=[a-z0-9])(?=[A-Z]))/);
  for (let i = 0; i < tokens.length; i++) {
    const swap = SYNONYM_OF.get(tokens[i].toLowerCase());
    if (!swap) continue;
    const next = tokens.slice();
    next[i] = matchCase(tokens[i], swap);
    const out = next.join('');
    if (out !== value) return { value: out, transform: 'synonym' };
  }
  const sep = value.includes('_') ? '_' : value.includes('-') ? '-' : /[a-z][A-Z]/.test(value) ? '' : '-';
  const out = sep === '' ? `${value}Legacy` : `${value}${sep}legacy`;
  return { value: out, transform: 'stale-id' };
}

/** The crude control condition (`--mode strip`): a value that describes nothing at all. */
function deadValue(seed) {
  let h = 0;
  for (const ch of String(seed)) h = (h * 33 + ch.charCodeAt(0)) >>> 0;
  return `sl-dead-${h.toString(36)}`;
}

// --- one candidate ------------------------------------------------------------

/**
 * A memo shared across one step's whole chain, so the same original string
 * drifts to the same replacement in every rung it appears in — a rename is one
 * event, and a chain that renamed its testid one way and the same testid
 * inside its css path another way is not a recording anything ever made.
 */
export function renameMemo(mode = 'rename') {
  const seen = new Map();
  return {
    mode,
    wording(text) {
      if (text === undefined || text === null) return null;
      const key = `w:${text}`;
      if (!seen.has(key)) {
        seen.set(key, mode === 'strip' ? (/\{\{/.test(text) ? null : { value: deadValue(text), transform: 'dead' }) : driftWording(text));
      }
      return seen.get(key);
    },
    identifier(value) {
      if (value === undefined || value === null) return null;
      const key = `i:${value}`;
      if (!seen.has(key)) {
        seen.set(key, mode === 'strip' ? (/\{\{/.test(value) ? null : { value: deadValue(value), transform: 'dead' }) : driftIdentifier(value));
      }
      return seen.get(key);
    },
  };
}

/**
 * Rewrite the quoted strings, ids and positions inside a selector — the css
 * rungs, and a scoped rung's container.
 *
 * Quoted strings go through the WORDING memo (a `[data-testid="add-part"]` or
 * a `role=button[name="Add part"]` in a css rung is the same fact as the
 * testid/role rung beside it and must drift with it), `#id` tokens through the
 * identifier memo, and a path with neither is a position rather than a
 * description: its last index is bumped, which is what a moved control does to
 * a recorded path.
 *
 * A slot (`{{v2}}`) is never touched: it names the RECORD this run is working
 * on, not the control, and a chain whose slot stopped filling is dropped by
 * `fillableChain` before it ever reaches a healer.
 */
/**
 * Is the quoted string at `at` a human-facing PHRASE or a machine IDENTIFIER?
 *
 * It has to be decided from context, not from the string's shape. A recorded
 * primary is often the raw engine selector beside its structured twin —
 * `role=textbox[name="Password"]` sits in the same chain as
 * `getByRole('textbox', { name: 'Password' })` — and judging "Password" by its
 * shape made the css rung drift to `Password-legacy` while the role rung
 * drifted to `Password…`. Two renames of one control in one chain is not a
 * recording anything ever made, and the whole point of the memo is that a
 * rename is ONE event.
 */
function quotedIsWording(selector, at) {
  const before = selector.slice(Math.max(0, at - 24), at);
  if (/(?:^|[\s>|])(?:text|:has-text\(|:text-is\()\s*=?\s*$/.test(before) || /:has-text\($|:text-is\($/.test(before)) return true;
  if (/aria-label\s*=\s*$/.test(before)) return true;
  // `[name="…"]` is an accessible name inside a role engine selector and a
  // form control's name attribute anywhere else.
  if (/\[name\s*=\s*$/.test(before)) return /\brole\s*=/.test(selector);
  if (/(?:data-[\w-]+|id|class|for|placeholder|type|value)\s*=\s*$/.test(before)) return /placeholder\s*=\s*$/.test(before);
  return false;
}

export function driftSelector(selector, memo) {
  if (!selector) return null;
  let transform = null;
  let out = selector.replace(/"([^"]*)"/g, (whole, inner, at) => {
    if (/\{\{/.test(inner)) return whole;
    const drifted = quotedIsWording(selector, at) ? memo.wording(inner) : memo.identifier(inner);
    if (!drifted) return whole;
    transform ??= drifted.transform;
    return `"${drifted.value}"`;
  });
  if (out !== selector) return { value: out, transform };

  out = selector.replace(/#([A-Za-z][\w-]*)/, (whole, id) => {
    const drifted = memo.identifier(id);
    if (!drifted) return whole;
    transform ??= drifted.transform;
    return `#${drifted.value}`;
  });
  if (out !== selector) return { value: out, transform: transform ?? 'stale-id' };

  // Purely positional: no name in it to have been renamed. Move it. A path
  // with an index is moved by bumping the index (which is what a reordered
  // page does to a recorded path); one without gets Playwright's own `>> nth=`
  // suffix rather than a css pseudo-class, because a malformed selector
  // resolves as an ERROR and this harness must produce a clean miss.
  const positions = [...selector.matchAll(/:nth-(?:of-type|child)\((\d+)\)/g)];
  if (positions.length) {
    const last = positions[positions.length - 1];
    const bumped = `${selector.slice(0, last.index)}${last[0].replace(/\d+/, String(Number(last[1]) + 7))}${selector.slice(last.index + last[0].length)}`;
    return { value: bumped, transform: 'moved-path' };
  }
  return { value: `${selector} >> nth=96`, transform: 'moved-path' };
}

/**
 * The drifted twin of one recorded candidate, or null when this rung cannot be
 * drifted (every part of it is a slot). Same `kind`, same shape, same families
 * — the recorded KIND is what `candidateRows` pre-filters the ballot on and
 * what `refuse()` checks the pick against, so changing it would change the
 * question rather than the answer.
 */
export function perturbCandidate(candidate, memo) {
  const c = candidate;
  const keep = (patch, transform) => ({ candidate: { ...c, ...patch }, transform });
  switch (c.kind) {
    case 'testid': {
      const d = memo.identifier(c.value);
      return d ? keep({ value: d.value }, d.transform) : null;
    }
    case 'role': {
      const d = memo.wording(c.name);
      return d ? keep({ name: d.value }, d.transform) : null;
    }
    case 'label': {
      const d = memo.wording(c.label);
      return d ? keep({ label: d.value }, d.transform) : null;
    }
    case 'placeholder': {
      const d = memo.wording(c.placeholder);
      return d ? keep({ placeholder: d.value }, d.transform) : null;
    }
    case 'text': {
      const d = memo.wording(c.text);
      return d ? keep({ text: d.value }, d.transform) : null;
    }
    case 'id':
    case 'css': {
      const d = driftSelector(c.selector, memo);
      return d ? keep({ selector: d.value }, d.transform) : null;
    }
    case 'scoped': {
      // `hasText` names the RECORD (it carries a caller-vouched value and is
      // re-bound every replay); only the container and the inner selector
      // describe the control, so only they drift.
      // One rename event: if the container drifted, the inner selector is left
      // alone — the rung is already dead, and drifting both would describe a
      // page that was renamed and restructured in the same breath.
      const container = driftSelector(c.container, memo);
      const inner = container ? null : c.selector ? driftSelector(c.selector, memo) : null;
      if (!container && !inner) return null;
      return keep(
        { ...(container ? { container: container.value } : {}), ...(inner ? { selector: inner.value } : {}) },
        container?.transform ?? inner?.transform ?? 'stale-path',
      );
    }
    case 'point':
      // A point resolves by finding something of the recorded KIND where the
      // element used to be. A moved control leaves nothing there, so the point
      // is pushed off the document: markPoint scrolls, finds nothing under the
      // coordinate and reports `unmarked`, exactly as it does for the real
      // relocation in bench/jev-heal-demo.mjs's `add-part-moved`.
      return keep({ y: c.y + c.vh * 4 + 1000 }, 'moved');
    default:
      return null;
  }
}

/**
 * The drifted twin of a whole chain, plus the per-rung transforms.
 *
 * `headline` is the transform the CASE is filed under, and it is the hardest
 * family present rather than the first rung's: what the chooser reads is
 * `deadLocators`, the WHOLE chain, so the case is as hard as its most
 * informative rung. A chain carrying a renamed accessible name is a synonym
 * case even if its testid merely went stale; a chain with no wording in it at
 * all is filed under the identifier or path family it does have, because that
 * is genuinely what it is — a step whose recording never named its control.
 */
const HEADLINE_ORDER = ['synonym', 'affix', 'punctuation', 'dead', 'stale-id', 'stale-path', 'moved-path', 'moved'];

export function perturbChain(chain, mode = 'rename') {
  const memo = renameMemo(mode);
  const rungs = [];
  const out = chain.map((c) => {
    const drifted = perturbCandidate(c, memo);
    rungs.push({ kind: c.kind, transform: drifted?.transform ?? null });
    return drifted ? drifted.candidate : c;
  });
  const present = new Set(rungs.map((r) => r.transform).filter(Boolean));
  const headline = HEADLINE_ORDER.find((f) => present.has(f)) ?? 'none';
  const undrifted = rungs.filter((r) => !r.transform).map((r) => r.kind);
  return { chain: out, rungs, headline, undrifted };
}

// --- reading a heal's answer back --------------------------------------------

/**
 * Parse `detail.pickedRow` — the line `renderSnapshotRow` produced for the row
 * Jev chose — back into a SnapshotRow.
 *
 * This is how a DEFERRED pick still gets scored. A run at gate 0 acts on every
 * pick that clears the code guards and files a drift ticket carrying the
 * proposal object, but a pick the guards refuse (matched two elements, wrong
 * kind) never becomes a ticket, and those are precisely the rows the gate has
 * to be calibrated against. The rendered line is the only record of them.
 */
export function parsePickedRow(line) {
  if (!line || typeof line !== 'string') return null;
  const row = {};
  const head = line.match(/^([A-Za-z][\w-]*)/);
  if (!head) return null;
  row.tag = head[1];
  for (const [, key, quoted, bare] of line.matchAll(/\b(role|id|testid|label|placeholder|text)=(?:"((?:[^"\\]|\\.)*)"|(\S+))/g)) {
    row[key] = quoted !== undefined ? JSON.parse(`"${quoted}"`) : bare;
  }
  return row;
}

/**
 * The identifying fields of a candidate, as a map of field -> value.
 *
 * Only fields an element can hold exactly ONE of, because that uniqueness is
 * the whole basis of the verdict below: two locators that disagree about a
 * testid, an id, or an accessible name for the same role cannot be naming the
 * same element on a page that has not changed.
 */
export function identityOf(candidate) {
  const c = candidate;
  if (!c) return {};
  switch (c.kind) {
    case 'testid':
      return { testid: c.value };
    case 'role':
      return { [`name:${c.role}`]: c.name };
    case 'label':
      return { label: c.label };
    case 'placeholder':
      return { placeholder: c.placeholder };
    case 'id': {
      const m = c.selector.match(/^#([\w-]+)$/) ?? c.selector.match(/^\[id="?([^"\]]+)"?\]$/);
      return m ? { id: m[1] } : {};
    }
    case 'text':
      return { text: c.text };
    case 'css': {
      const out = {};
      const testid = c.selector.match(/\[data-testid="([^"]+)"\]/);
      if (testid) out.testid = testid[1];
      const id = c.selector.match(/^#([\w-]+)$/);
      if (id) out.id = id[1];
      const role = c.selector.match(/^role=([a-z]+)\[name="([^"]+)"\]$/);
      if (role) out[`name:${role[1]}`] = role[2];
      return out;
    }
    default:
      return {};
  }
}

/**
 * Is this proposal the element the ORIGINAL chain names?
 *
 * The app did not change, so the original chain still names the right control,
 * and it names it several ways at once. Agreement on any identifying field is
 * proof of the same element; disagreement on one is proof of a different one.
 * Everything else is `undecidable` — a proposal that names the control by
 * something the recording never recorded (a bare text, a label where the
 * recording only had a testid) may be right or wrong and this harness has no
 * way to say, so it is reported and counted in neither column.
 */
export function judgeProposal(proposal, originalChain) {
  const mine = identityOf(proposal);
  if (!Object.keys(mine).length) return { verdict: 'undecidable', why: `a ${proposal?.kind ?? 'null'} locator carries no identifying field` };
  const conflicts = [];
  for (const candidate of originalChain ?? []) {
    const theirs = identityOf(candidate);
    for (const [field, value] of Object.entries(mine)) {
      if (!(field in theirs)) continue;
      if (theirs[field] === value) return { verdict: 'correct', why: `agrees with the recorded chain on ${field}=${JSON.stringify(value)}` };
      conflicts.push(`${field}: proposed ${JSON.stringify(value)}, recorded ${JSON.stringify(theirs[field])}`);
    }
  }
  if (conflicts.length) return { verdict: 'wrong', why: conflicts[0] };
  return { verdict: 'undecidable', why: `nothing in the recorded chain shares a field with a ${proposal.kind} locator` };
}

// --- the tables ---------------------------------------------------------------

export const CONFIDENCE_BUCKETS = [
  [0, 0.5],
  [0.5, 0.6],
  [0.6, 0.7],
  [0.7, 0.8],
  [0.8, 0.9],
  [0.9, 1.0001],
];

export function bucketLabel(confidence) {
  for (const [lo, hi] of CONFIDENCE_BUCKETS) {
    if (confidence >= lo && confidence < hi) return `${lo.toFixed(2)}–${Math.min(hi, 1).toFixed(2)}`;
  }
  return 'n/a';
}

/**
 * Accuracy by confidence bucket over every case that was ASKED and decided —
 * the reliability curve the gate is read off. Deferred picks are in it: the
 * whole point of running at gate 0 is that a pick below the gate is observed
 * rather than censored, and a curve built only from picks that cleared a gate
 * cannot say anything about where the gate belongs.
 */
export function reliability(cases) {
  const rows = new Map();
  for (const [lo, hi] of CONFIDENCE_BUCKETS) rows.set(`${lo.toFixed(2)}–${Math.min(hi, 1).toFixed(2)}`, { correct: 0, wrong: 0, undecidable: 0 });
  for (const c of cases) {
    if (!c.asked || c.confidence === null) continue;
    const row = rows.get(bucketLabel(c.confidence));
    if (!row) continue;
    if (c.verdict === 'correct') row.correct++;
    else if (c.verdict === 'wrong') row.wrong++;
    else row.undecidable++;
  }
  return [...rows].map(([bucket, r]) => ({
    bucket,
    ...r,
    n: r.correct + r.wrong,
    accuracy: r.correct + r.wrong ? r.correct / (r.correct + r.wrong) : null,
  }));
}

/**
 * What each candidate gate would have done on this data.
 *
 * A case is ACCEPTED at gate g when Jev picked something, the two option
 * orders agreed, the gone-noul did not veto, the code guards passed, and the
 * confidence is >= g — i.e. every guard site B actually runs, evaluated at
 * that gate. `wrong` counts false accepts, which is the only column that can
 * veto a gate; `healRate` is the share of dead-chain steps the gate rescues,
 * which is the only column that can recommend one.
 */
export function gateTable(cases, gates) {
  const dead = cases.filter((c) => c.deadChain).length;
  return gates.map((gate) => {
    const accepted = cases.filter((c) => c.guardsPassed && c.confidence !== null && c.confidence >= gate);
    const wrong = accepted.filter((c) => c.verdict === 'wrong');
    const correct = accepted.filter((c) => c.verdict === 'correct');
    return {
      gate,
      accepted: accepted.length,
      correct: correct.length,
      wrong: wrong.length,
      undecidable: accepted.length - correct.length - wrong.length,
      healRate: dead ? accepted.length / dead : null,
      wrongCases: wrong.map((c) => c.id),
    };
  });
}

/** Split any list of cases by a key, with the same correct/wrong/undecidable counts. */
export function splitBy(cases, key) {
  const out = new Map();
  for (const c of cases) {
    const k = String(c[key] ?? '?');
    const row = out.get(k) ?? { key: k, cases: 0, asked: 0, correct: 0, wrong: 0, undecidable: 0, confidences: [] };
    row.cases++;
    if (c.asked) {
      row.asked++;
      if (c.verdict === 'correct') row.correct++;
      else if (c.verdict === 'wrong') row.wrong++;
      else row.undecidable++;
      if (c.confidence !== null) row.confidences.push(c.confidence);
    }
    out.set(k, row);
  }
  return [...out.values()]
    .map((r) => ({
      ...r,
      medianConfidence: r.confidences.length ? median(r.confidences) : null,
      confidences: undefined,
    }))
    .sort((a, b) => b.cases - a.cases);
}

export function median(xs) {
  const s = [...xs].sort((a, b) => a - b);
  const mid = s.length >> 1;
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
}

/**
 * The lowest gate with ZERO wrong accepts, and how many cases stand behind it.
 *
 * Deliberately not "the gate with the best F1": a wrong accept is a click on
 * the wrong control with nothing between it and the app, and n is reported
 * beside the number because the recommendation this replaces was made on n=4.
 */
export function recommendGate(table) {
  const clean = table.filter((r) => r.wrong === 0);
  if (!clean.length) return { gate: null, why: 'every gate on this data accepts at least one wrong pick' };
  const best = clean.reduce((a, b) => (b.gate < a.gate ? b : a));
  return {
    gate: best.gate,
    accepted: best.accepted,
    correct: best.correct,
    undecidable: best.undecidable,
    healRate: best.healRate,
    why: `lowest gate with no false accepts; ${best.correct} correct accept(s) support it`,
  };
}
