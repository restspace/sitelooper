const dirs: string[] = [];
const saved: Record<string, string | undefined> = {};
const ENV = ['SITELOOPER_HOME', 'SITELOOPER_SKILLS_DIR', 'SITELOOPER_FLOWS_DIR', 'SITELOOPER_COMPONENTS_FILE'];

function temp(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sl-readable-'));
  dirs.push(dir);
  return dir;
}

beforeEach(() => {
  const home = temp();
  for (const k of ENV) saved[k] = process.env[k];
  // Hermetic: no machine's skill, flow, component or facts store leaks in.
  process.env.SITELOOPER_HOME = home;
  process.env.SITELOOPER_SKILLS_DIR = path.join(home, 'skills');
  process.env.SITELOOPER_FLOWS_DIR = path.join(home, 'flows');
  process.env.SITELOOPER_COMPONENTS_FILE = path.join(home, 'components.json');
});
afterEach(() => {
  for (const k of ENV) {
    if (saved[k] === undefined) delete process.env[k];
    else process.env[k] = saved[k];
  }
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

const skill = (id = 's_open', url = 'http://app.test/items'): Skill => ({
  id, origin: 'http://app.test', template: 'open items', params: {},
  preconditions: { urlPattern: 'http://app.test/' },
  steps: [{ tool: 'goto', args: { url }, locators: {} }],
  stats: { uses: 2, successes: 2, partial: 0, created: '2026-09-07T00:00:00.000Z', failedAtStep: {}, fallthroughs: 0 },
  status: 'validated',
  provenance: { session: 'author', instruction: 'open items', created: '2026-09-07T00:00:00.000Z' },
});

const flowOf = (skillId = 's_open'): Flow => ({
  name: 'items', origin: 'http://app.test', startUrl: 'http://app.test/', vars: [],
  steps: [{ id: '01-open', instruction: 'open items', skill: skillId, outputs: [], recorded: {} }],
  provenance: { session: 'author', created: '2026-09-07T00:00:00.000Z' },
});

/** A project dir with a bundle at .sitelooper/procedures.json and an output dir. */
function project(): { dir: string; bundle: string; out: string; store: SkillStore; flowFile: string } {
  const dir = temp();
  const store = new SkillStore(path.join(dir, 'skills'));
  store.put(skill());
  const flowFile = saveFlow(flowOf(), path.join(dir, 'items.json'));
  const bundle = path.join(dir, '.sitelooper', 'procedures.json');
  exportFlowBundle(flowFile, { outFile: bundle, store });
  return { dir, bundle, out: path.join(dir, 'tests', 'sitelooper'), store, flowFile };
}

const read = (file: string) => fs.readFileSync(file, 'utf8');

describe('style selection on compile', () => {
  it('resolves --style over the file on disk over the project config over runtime', () => {
    expect(resolveStyle({})).toBe('runtime');
    expect(resolveStyle({ configured: 'readable' })).toBe('readable');
    expect(resolveStyle({ existing: 'runtime', configured: 'readable' })).toBe('runtime');
    expect(resolveStyle({ explicit: 'runtime', existing: 'readable', configured: 'readable' })).toBe('runtime');
    expect(resolveStyle({ explicit: 'readable', existing: 'runtime' })).toBe('readable');
  });

  it('writes the readable file with its source line pointing at the bundle, relative to the file', () => {
    const p = project();
    const result = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    expect(result.style).toBe('readable');
    expect(result.flowFile).toBe(path.join(p.out, 'items.flow.ts'));
    const source = read(result.flowFile!);
    expect(isReadableFlowFile(source)).toBe(true);
    // No runtime "Generated by" line prepended: the readable header is the emitter's own.
    expect(source.startsWith('// Generated by sitelooper ')).toBe(true);
    expect(source).toContain('(readable style)');
    expect(source).not.toContain('@sitelooper-flow-begin');
    const meta = readableSource(source);
    expect(meta).toMatchObject({ flow: 'items', bundle: '../../.sitelooper/procedures.json' });
    expect(meta.specHash).toBe(readableSpecHash(result.spec));
    expect(result.warnings).toContain('the readable style has no run-time locator fallback');
    // The scaffold is the same user-owned spec.ts either way.
    expect(read(result.specFile!)).toContain("from './items.flow'");
  });

  it('a recompile keeps the existing file style unless --style says otherwise', () => {
    const p = project();
    compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const file = path.join(p.out, 'items.flow.ts');
    // No style asked for, and a project default of runtime: the file stays readable.
    expect(compileFlow(p.bundle, { outDir: p.out, defaultStyle: 'runtime' }).style).toBe('readable');
    expect(flowFileStyle(read(file))).toBe('readable');
    // --style runtime converts it; the next plain recompile then keeps runtime, even with a readable default.
    expect(compileFlow(p.bundle, { outDir: p.out, style: 'runtime' }).style).toBe('runtime');
    expect(flowFileStyle(read(file))).toBe('runtime');
    expect(compileFlow(p.bundle, { outDir: p.out, defaultStyle: 'readable' }).style).toBe('runtime');
    expect(read(file)).toContain('@sitelooper-flow-begin');
  });

  it('the project default applies to a new file only, and runtime stays the default', () => {
    const p = project();
    expect(compileFlow(p.bundle, { outDir: path.join(p.dir, 'a') }).style).toBe('runtime');
    expect(compileFlow(p.bundle, { outDir: path.join(p.dir, 'b'), defaultStyle: 'readable' }).style).toBe('readable');
  });

  it('a project snapshot compiled by flow name is the bundle the source line names', () => {
    const p = project();
    const result = compileFlow('items', { outDir: p.out, snapshotFile: p.bundle, style: 'readable' });
    expect(readableSource(read(result.flowFile!)).bundle).toBe('../../.sitelooper/procedures.json');
  });

  it('a flow from the user store records a null bundle', () => {
    const p = project();
    const result = compileFlow(p.flowFile, { outDir: p.out, store: p.store, style: 'readable' });
    expect(readableSource(read(result.flowFile!)).bundle).toBeNull();
  });

  it('compiling a readable flow file compiles its recording again, next to the file', () => {
    const p = project();
    const first = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    fs.writeFileSync(first.flowFile!, read(first.flowFile!) + '\n// hand edit\n');
    const again = compileFlow(first.flowFile!, {});
    expect(again.flowFile).toBe(first.flowFile);
    expect(again.style).toBe('readable');
    expect(read(first.flowFile!)).not.toContain('hand edit');
  });
});

describe('lifting a readable flow file', () => {
  it('rebuilds the SpecFlow compile emitted, through the bundle, with no warning when it is current', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const lifted = liftReadableFlowFile(compiled.flowFile!);
    expect(lifted.warnings).toEqual([]);
    expect(lifted.spec).toEqual(compiled.spec);
    expect(lifted.spec).toEqual(recordedSpec(p.bundle).spec);
    expect(lifted.target.bundleFile).toBe(path.resolve(p.bundle));
  });

  it('warns that the file is stale when the bundle moved on, and proceeds with the bundle', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    p.store.put(skill('s_open', 'http://app.test/items?page=2'), { overwrite: true });
    exportFlowBundle(p.flowFile, { outFile: p.bundle, store: p.store });
    const lifted = liftReadableFlowFile(compiled.flowFile!);
    expect(lifted.warnings).toHaveLength(1);
    expect(lifted.warnings[0]).toMatch(/items\.flow\.ts is stale/);
    expect(lifted.warnings[0]).toContain('--style readable');
    expect(JSON.stringify(lifted.spec)).toContain('page=2');
  });

  it('falls back to the project snapshot, then the user store, when the named bundle is gone', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const moved = path.join(p.dir, 'elsewhere.json');
    fs.renameSync(p.bundle, moved);
    expect(liftReadableFlowFile(compiled.flowFile!, { snapshotFile: moved }).target.bundleFile).toBe(path.resolve(moved));
    // The user store: the flow saved under SITELOOPER_FLOWS_DIR.
    saveFlow(flowOf(), path.join(process.env.SITELOOPER_FLOWS_DIR!, 'items.json'));
    expect(readableTarget(compiled.flowFile!)).toMatchObject({ target: 'items', bundleFile: null });
    fs.rmSync(path.join(process.env.SITELOOPER_FLOWS_DIR!, 'items.json'));
    expect(() => readableTarget(compiled.flowFile!)).toThrow(LiftError);
  });

  it('the FLOW lift names the readable style instead of calling the file foreign', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    expect(() => liftFlowFile(read(compiled.flowFile!))).toThrow(/readable-style flow file/);
  });

  it('refuses a readable file whose source line is missing or malformed, naming it', () => {
    expect(() => readableSource('// @sitelooper-readable v1\n')).toThrow(/no "\/\/ @sitelooper-source" line/);
    expect(() => readableSource('// @sitelooper-readable v1\n// @sitelooper-source {nope\n')).toThrow(/not valid JSON/);
    expect(flowFileStyle('// nothing\n')).toBeNull();
  });
});

const passing = (steps: string[]): SpecCheckResult => ({
  ran: true, passed: true, outcome: 'passed', executedSteps: steps, drift: [], driftCount: 0,
} as unknown as SpecCheckResult);

describe('readiness on a readable flow file', () => {
  it('reads its metadata exports and verifies, with no FLOW constant to lift', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const check = vi.fn(() => passing(['01-open']));
    const report = runReadinessCheck({ flowFile: compiled.flowFile!, fixtureIsolation: true, runs: 2 }, check);
    expect(report.blockers).toEqual([]);
    expect(report.outcome).toBe('verified');
    expect(check).toHaveBeenCalledTimes(2);
    expect(report.warnings).toEqual([]);
  });

  it('blocks a run that did not complete a step the metadata lists', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const report = runReadinessCheck({ flowFile: compiled.flowFile!, fixtureIsolation: true, runs: 1 }, () => passing([]));
    expect(report.outcome).toBe('failed');
    expect(report.blockers.join(' ')).toContain('Required steps did not complete: 01-open');
  });

  it('carries the stale-file warning, and an unfindable recording is a warning, not invalid metadata', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    p.store.put(skill('s_open', 'http://app.test/items?page=3'), { overwrite: true });
    exportFlowBundle(p.flowFile, { outFile: p.bundle, store: p.store });
    const stale = runReadinessCheck({ flowFile: compiled.flowFile!, fixtureIsolation: true, runs: 1 }, () => passing(['01-open']));
    expect(stale.outcome).toBe('verified');
    expect(stale.warnings.join(' ')).toMatch(/is stale/);
    fs.rmSync(p.bundle);
    const lost = runReadinessCheck({ flowFile: compiled.flowFile!, fixtureIsolation: true, runs: 1 }, () => passing(['01-open']));
    expect(lost.outcome).toBe('verified');
    expect(lost.blockers.join(' ')).not.toContain('Compiled metadata is invalid');
    expect(lost.warnings.join(' ')).toContain('could not be loaded');
  });
});

describe('rerecord and repair on a readable flow file', () => {
  it('rerecord resolves the readable file to its bundle, and recompiles it readable in place', () => {
    const p = project();
    const compiled = compileFlow(p.bundle, { outDir: p.out, style: 'readable' });
    const input = resolveRerecordInput(compiled.flowFile!);
    expect(input).toMatchObject({ kind: 'bundle', file: path.resolve(p.bundle), readable: { flowFile: path.resolve(compiled.flowFile!) } });
    expect(input.flow.name).toBe('items');
    // The bundle moves on (as a successful re-record writes it), then the recompile follows it.
    p.store.put(skill('s_open', 'http://app.test/items?page=4'), { overwrite: true });
    exportFlowBundle(p.flowFile, { outFile: p.bundle, store: p.store });
    const re = recompileAfterRerecord(input, {});
    expect(re?.style).toBe('readable');
    expect(re?.flowFile).toBe(compiled.flowFile);
    expect(liftReadableFlowFile(compiled.flowFile!).warnings).toEqual([]);
    // --style runtime on the re-record converts it.
    expect(recompileAfterRerecord(input, { style: 'runtime' })?.style).toBe('runtime');
  });

  it('a bundle re-record recompiles only when --style asks for it', () => {
    const p = project();
    const input = resolveRerecordInput(p.bundle);
    expect(recompileAfterRerecord(input, {})).toBeNull();
    const re = recompileAfterRerecord(input, { style: 'readable', outDir: p.out });
    expect(re?.flowFile).toBe(path.join(p.out, 'items.flow.ts'));
    expect(re?.style).toBe('readable');
  });

  it('repair refuses --propose, --dry-run and --out on a readable spec, naming rerecord and compile', () => {
    expect(readableRepairRefusal('t/items.flow.ts', {})).toBeNull();
    const msg = readableRepairRefusal('t/items.flow.ts', { propose: true, dryRun: true });
    expect(msg).toContain('--propose, --dry-run');
    expect(msg).toContain('sitelooper rerecord t/items.flow.ts <step-id>');
    expect(msg).toContain('sitelooper compile <bundle> --style readable');
    expect(readableRepairRefusal('x.flow.ts', { out: true })).toContain('--out');
  });
});

describe('cli wiring (source level: importing src/cli.ts runs main())', () => {
  const cli = fs.readFileSync(path.resolve(__dirname, '../src/cli.ts'), 'utf8');

  it('parses --style as a value flag and validates it', () => {
    const valueFlags = cli.match(/const valueFlags = new Set\(\[([\s\S]*?)\]\);/)?.[1] ?? '';
    expect(valueFlags).toContain("'style'");
    expect(cli).toContain('if (!isSpecStyle(value)) fail(`--style takes readable or runtime');
  });

  it('documents --style on compile, build and rerecord, and the readable repair', () => {
    expect(cli).toMatch(/compile <flow-or-bundle> [^\n]*\[--style readable\|runtime\]/);
    expect(cli).toMatch(/build <flow-or-bundle> [^\n]*\[--style readable\|runtime\]/);
    expect(cli).toMatch(/\[--runs N\] \[--var k=v\] \[--reset-cmd "<command>"\] \[--style readable\|runtime\]/);
    expect(cli).toContain('On a readable spec, repair runs the spec once');
  });

  it('every compiling command shares the style options, and build/converge/repair compile through them', () => {
    expect(cli).toContain('style: styleFlag(flags),');
    expect(cli).toContain('defaultStyle: project.style,');
    expect(cli.match(/compileFlow\([^)]*compileOptions\(|compileFlow\(positional\[0\], options\)|compileFlow\(flowNameOrPath, options\)/g)?.length).toBe(3);
  });

  it('repair branches to the readable path before the FLOW lift', () => {
    const body = cli.slice(cli.indexOf('async function repairFlowCommand'));
    expect(body.indexOf('if (isReadableFlowFile(source)) return repairReadableCommand(')).toBeGreaterThan(0);
    expect(body.indexOf('if (isReadableFlowFile(source)) return repairReadableCommand(')).toBeLessThan(body.indexOf('before = liftFlowFile(source).spec;'));
    const readable = cli.slice(cli.indexOf('async function repairReadableCommand'), cli.indexOf('// --- rerecord one step'));
    expect(readable).toContain('readableRepairRefusal(file,');
    expect(readable).toContain('await convergeLoop([file], sub, json, onProgress, rounds, hasModelKey)');
    expect(readable).toContain("stage: 'repair', file, style,");
  });

  it('result documents carry the style', () => {
    expect(cli).toContain("emitJson({ style: compilation?.style ?? fileStyle(file), ...extra");
    expect(cli).toContain('emitJson({ file, style: fileStyle(file), specCheck: result }');
    expect(cli).toContain("style: recompiled?.style ?? (input.readable ? 'readable'");
  });
});
