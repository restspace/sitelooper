// The wiring of the readable output style (notes: readable-contract): style
// selection on compile, the style a recompile keeps, the lift of a readable
// file through its bundle, readiness and rerecord on one, and what repair
// refuses. The emitter itself (src/spec/emit-readable.ts) is a sibling's and
// is stubbed here with a file carrying the contract's marker lines and
// metadata exports, so these tests pin the wiring and nothing else.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

vi.mock('../src/spec/emit-readable.js', async () => {
  const { readableSpecHash } = await import('../src/spec/lift.js');
  return {
    emitReadableFlowFile: (spec: import('../src/spec/ir.js').SpecFlow, o: { compilerVersion: string; bundleRelPath: string | null }) => ({
      source: [
        `// Generated by sitelooper ${o.compilerVersion} from flow "${spec.name}" (readable style) — regenerate, don't edit:`,
        `//   sitelooper compile ${o.bundleRelPath ?? spec.name} --style readable`,
        '// @sitelooper-readable v1',
        `// @sitelooper-source ${JSON.stringify({ flow: spec.name, bundle: o.bundleRelPath, specHash: readableSpecHash(spec) })}`,
        "import { test } from '@playwright/test';",
        `export const flowStepIds = ${JSON.stringify(spec.steps.map((s) => s.id))} as const;`,
        `export const requiredInputNames = ${JSON.stringify(spec.vars)} as const;`,
        'export const requiredEnvNames = [] as const;',
        ...spec.steps.map((s) => `// @step ${s.id} ${s.segments[0]?.id ?? 'none'}/0`),
        '',
      ].join('\n'),
      warnings: ['the readable style has no run-time locator fallback'],
    }),
  };
});

